  // exampleRank(id, query) → examples ordered by relevance to the request:
  // tag / title word overlap (stemmed lightly), ties keep library order. Pure
  // and deterministic - the same query gives the same order; returns every
  // example with its score so callers can explain the pick.
  const stemWord = (w) => (w.length >= 5 ? w.replace(/(ies)$/, "y").replace(/(sh|ch|ss|x|z)es$/, "$1").replace(/([^s])s$/, "$1").replace(/ing$/, "").replace(/ed$/, "") : w);
  function exampleRank(id, query) {
    const ex = examples(id);
    const q = String(query || "").toLowerCase();
    const words = new Set(q.split(/[^a-z0-9]+/).filter((w) => w.length >= 3).map(stemWord));
    return ex.map((e, i) => {
      let score = 0; const hits = [];
      for (const t of e.tags || []) {
        const parts = String(t).toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
        if (parts.length > 1 ? q.includes(t.toLowerCase()) : words.has(stemWord(parts[0] || ""))) { score += parts.length > 1 ? 3 : 2; hits.push(t); }
      }
      for (const w of String(e.title).toLowerCase().split(/[^a-z0-9]+/)) if (w.length >= 4 && words.has(stemWord(w))) score += 1;
      return { example: e, score, hits, order: i };
    }).sort((a, b) => b.score - a.score || a.order - b.order);
  }
